const GenericIcon: React.FC<IconProps> = ({ className = "w-4 h-4" }) => <Globe className={className} aria-hidden="true" />;

const ICONS: Record<string, React.FC<IconProps>> = {
  facebook: FacebookIcon,
  linkedin: LinkedinIcon,
  x: XIcon,
  twitter: XIcon,
  instagram: InstagramIcon,
  youtube: YoutubeIcon,
};

/** Inline SVG icon for a platform key; unknown platforms get a globe. */
export function SocialIcon({ platform, className }: { platform: string } & IconProps) {
  const Icon = ICONS[platform] ?? GenericIcon;
  return <Icon className={className} />;
}

/**
 * Uploaded custom icon when set (Admin > Contact Settings > Social Media Links),
 * otherwise the built-in icon for the platform.
 */
export function PlatformIcon({ platform, iconUrl, className = "w-4 h-4" }: { platform: string; iconUrl?: string | null } & IconProps) {
  if (iconUrl) {
    // eslint-disable-next-line @next/next/no-img-element
    return <img src={iconUrl} alt="" loading="lazy" decoding="async" className={`${className} object-contain`} />;
  }
  return <SocialIcon platform={platform} className={className} />;
}

